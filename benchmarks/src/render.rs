//! Markdown rendering of the dataset: one single-stream table, one fan-out table.

use crate::{Dataset, Run, roofline_ratio, roofline_tok_s};
use std::fmt::Write;

fn opt(v: Option<f64>, prec: usize) -> String {
    v.map_or_else(|| "—".to_string(), |x| format!("{x:.prec$}"))
}

fn engine_cell(r: &Run) -> String {
    let mut s = format!("{} {}", r.engine, r.engine_version);
    if r.nodes > 1 {
        let _ = write!(s, " · {}× {}", r.nodes, r.parallelism.as_deref().unwrap_or(""));
    }
    s
}

fn model_cell(ds: &Dataset, r: &Run) -> String {
    ds.model(&r.model).map_or_else(|| r.model.clone(), |m| m.name.clone())
}

fn sorted(ds: &Dataset, pred: impl Fn(&Run) -> bool) -> Vec<&Run> {
    let mut v: Vec<&Run> = ds.runs.iter().filter(|r| pred(r)).collect();
    v.sort_by(|a, b| (&a.model, &a.date, &a.id).cmp(&(&b.model, &b.date, &b.id)));
    v
}

/// The whole TABLE.md.
pub fn markdown(ds: &Dataset) -> String {
    let mut out = String::new();
    out.push_str("# Benchmark table\n\nGenerated by `cargo run -- render` from `data/`. Do not edit by hand.\n\n");
    for h in &ds.hardware {
        let _ = writeln!(
            out,
            "**{}** (`{}`) — {:.2} GiB {}. Bandwidth: spec {} GB/s · STREAM copy {} GB/s · **decode roofline divisor {} GB/s**.\n",
            h.name,
            h.id,
            h.memory_gib,
            h.memory_kind.as_deref().unwrap_or(""),
            h.spec_bw_gbs,
            h.stream_copy_gbs,
            h.decode_bw_gbs
        );
    }
    out.push_str(
        "`% roofline` = measured ÷ (nodes × decode_bw_gbs ÷ active_gb_per_token). 100% = the anchor's \
         single-stream, no-speculation rate. Rows above 100% have speculation on or a better kernel path; \
         rows well below it are dequant-compute-bound or misconfigured. `—` = active bytes/token not derived \
         yet (see MEASURE-LATER.md).\n\n",
    );

    out.push_str("## Single-stream decode (concurrency 1)\n\n");
    out.push_str("| model | checkpoint | engine | quant | spec | ctx | decode tok/s | roofline tok/s | % roofline | prefill tok/s @ tokens | date | source |\n");
    out.push_str("|---|---|---|---|---|---|---|---|---|---|---|---|\n");
    for r in sorted(ds, |r| r.concurrency == 1) {
        let hw = ds.hardware(&r.hardware);
        let roof = hw.and_then(|h| roofline_tok_s(h, r));
        let pct = hw.and_then(|h| roofline_ratio(h, r)).map(|x| x * 100.0);
        let prefill = match (r.prefill_tok_s, r.prefill_prompt_tokens) {
            (Some(p), Some(n)) => format!("{p:.0} @ {n}"),
            _ => "—".into(),
        };
        let _ = writeln!(
            out,
            "| {} | {} | {} | {} | {} | {} | **{:.1}** | {} | {} | {} | {} | {} |",
            model_cell(ds, r),
            r.checkpoint,
            engine_cell(r),
            r.quant,
            r.speculation,
            r.context_tokens.map_or("—".into(), |c| c.to_string()),
            r.decode_tok_s,
            opt(roof, 1),
            pct.map_or("—".into(), |p| format!("{p:.0}%")),
            prefill,
            r.date,
            r.source
        );
    }

    out.push_str("\n## Fan-out decode (concurrency > 1, aggregate tok/s)\n\n");
    out.push_str("| model | engine | quant | spec | conc | aggregate tok/s | per stream | × single-stream roofline | date | source |\n");
    out.push_str("|---|---|---|---|---|---|---|---|---|---|\n");
    for r in sorted(ds, |r| r.concurrency > 1) {
        let mult = ds.hardware(&r.hardware).and_then(|h| roofline_ratio(h, r));
        let _ = writeln!(
            out,
            "| {} | {} | {} | {} | {} | **{:.1}** | {} | {} | {} | {} |",
            model_cell(ds, r),
            engine_cell(r),
            r.quant,
            r.speculation,
            r.concurrency,
            r.decode_tok_s,
            opt(r.decode_per_stream_tok_s, 1),
            mult.map_or("—".into(), |m| format!("{m:.2}×")),
            r.date,
            r.source
        );
    }

    out.push_str("\n## Notes per row\n\n");
    for r in sorted(ds, |_| true) {
        if let Some(n) = &r.notes {
            let _ = writeln!(out, "- `{}` — {}", r.id, n.trim());
        }
    }
    out
}
